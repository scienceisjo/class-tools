/* ═══════════════════════════════════════════════════════════════
   해누리중 공지 — 서비스워커
   ---------------------------------------------------------------
   "홈 화면에 추가"가 뜨게 하려면 서비스워커가 하나 있어야 합니다.
   다만 화면 내용을 저장해 두지는 않습니다.
   저장해 두면 프로그램이 옛날 것으로 굳어서, 공지를 고쳐도
   바뀌지 않은 것처럼 보이는 일이 생기기 때문입니다.
   ═══════════════════════════════════════════════════════════════ */
